import { mkdir, cp, copyFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { buildStaticSite } from './static-site.mjs';
const target = resolve('dist', 'beget-' + new Date().toISOString().replace(/[:.]/g, '-'));
await mkdir(target, { recursive: true });
await buildStaticSite({output:resolve(target,'public_html')});
await copyFile(resolve('contact.example.php'), resolve(target, 'contact.example.php'));
await copyFile(resolve('BEGET.md'), resolve(target, 'BEGET.md'));
await copyFile(resolve('FORM-SECURITY.txt'), resolve(target, 'FORM-SECURITY.txt'));
for (const file of ['SITE-SECURITY.txt', 'DDOS-BEGET.txt']) await copyFile(resolve(file), resolve(target, file));
