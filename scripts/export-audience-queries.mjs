const csv = rows => '\uFEFF'+rows.map(row=>row.map(v=>'"'+String(v).replaceAll('"','""')+'"').join(',')).join('\n')+'\n';
const typoRows = [['Правильная фраза','Вариант с опечаткой','Основная страница','Город / география','Статус спроса','Примечание']];
for(const alias of aliases) {
  const qualifiers = [['','Россия'],[' для бизнеса','Россия'],...cities.flatMap(([name,prep])=>[[' в '+prep,name],[' для бизнеса в '+prep,name]])];
  for(const [suffix,region] of qualifiers) {
    const phrase=alias+suffix;
    typoRows.push([phrase,phrase.replace('агентство','агенство'),'/',region,'Не проверено в Wordstat','Карта исследовательских вариантов; не список для вставки в страницу']);
  }
}
const model=await siteModel();
const painRows=[['Страница','Фраза / вопрос клиента','Размещение','Статус спроса','Частотность']];
const regionalRows=[['Страница','Город','Фраза-кандидат','Формат работы','Статус спроса','Частотность']];
for(const service of model.services) {
  const page='/services/'+service.slug;
  painRows.push([page,serviceProblemAnswers[service.slug][0],'Видимый FAQ','Не измерено','']);
  for(const phrase of extra[service.slug])painRows.push([page,phrase,'Идея для проверки; не обязательно буквальное вхождение','Не измерено','']);
  for(const [city,prep] of cities) {
    for(const phrase of [service.name+' в '+prep,service.name+' для бизнеса в '+prep])
      regionalRows.push([page,city,phrase,city==='Пермь'?'Пермское агентство, дистанционная работа':'Удалённое обслуживание; не местный офис','Не измерено','']);
  }
}
await Promise.all([
  writeFile('seo/agency-spelling-variants.csv',csv(typoRows)),
  writeFile('seo/audience-problem-queries.csv',csv(painRows)),
  writeFile('seo/regional-service-queries.csv',csv(regionalRows))
]);
console.log(`Exported ${typoRows.length-1} spelling pairs, ${painRows.length-1} audience queries, ${regionalRows.length-1} regional candidates. Frequencies not invented.`);
